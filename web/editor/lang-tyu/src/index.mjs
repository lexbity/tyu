// The Tyu language package for CodeMirror 6 (PLAN-WASM-2 FR-21): a
// self-contained `LanguageSupport` — parser (Lezer, generated from
// ../tyu.grammar), highlight style, indentation, and folding for definition
// bodies. It MUST NOT know the REPL, the session, or the DOM exists (R-G):
// its inputs are text and its outputs are editor facets.

import {
  LRLanguage,
  foldNodeProp,
  indentService,
  HighlightStyle,
  syntaxTree,
} from "@codemirror/language";
import { styleTags, tags as t, Tag } from "@lezer/highlight";

import { parser } from "./parser.js";

// Stack-effect signatures get their OWN tag class (R-W3: never lumped in
// with ordinary comments — they are load-bearing documentation, and the
// shipped highlight style renders them distinctly).
export const stackEffect = Tag.define();

// Node props ride on the PARSER (lezer), not the extension set: highlight
// classes and the fold/indent structure are parser configuration.
const tyuParser = parser.configure({
  props: [
    styleTags({
      "WordDef/Ident": t.definition(t.variableName),
      KwModule: t.moduleKeyword,
      "KwImport KwExport KwEnd KwAs KwNeeds KwType KwSubtype KwStruct KwEnum KwConst KwResource KwRegisterMap KwOwned KwIso": t.keyword,
      Number: t.integer,
      String: t.string,
      LineComment: t.lineComment,
      "WordDef/StackEffectComment StackEffectComment": stackEffect,
      "OpPlus OpMinus OpStar OpSlash OpLt OpGt OpLe OpGe OpEq OpNe": t.operator,
      ArrowBind: t.operator,
      AtSign: t.meta,
    }),
    foldNodeProp.add({
      WordDef: (node, state) => {
        const line = state.doc.lineAt(node.from);
        if (line.to >= node.to - 1) return null;
        return { from: line.to, to: node.to - 1 };
      },
      Quotation: (node) => {
        if (node.to - node.from < 2) return null;
        return { from: node.from + 1, to: node.to - 1 };
      },
    }),
  ],
});

const tyuLanguage = LRLanguage.define({
  parser: tyuParser,
  languageData: {
    commentTokens: { line: "#" },
    indentUnit: "  ",
    closeBrackets: { brackets: ["(", "[", '"'] },
  },
});

// The highlight style (FR-21). The class names are the contract with the
// served editor.css (generated by build.mjs) — one render surface.
export const tyuHighlightStyle = HighlightStyle.define([
  { tag: t.definition(t.variableName), class: "tyu-def" },
  { tag: t.moduleKeyword, class: "tyu-kw" },
  { tag: t.keyword, class: "tyu-kw" },
  { tag: t.integer, class: "tyu-number" },
  { tag: t.string, class: "tyu-string" },
  { tag: t.lineComment, class: "tyu-comment" },
  { tag: stackEffect, class: "tyu-sig" },
  { tag: t.operator, class: "tyu-op" },
  { tag: t.meta, class: "tyu-meta" },
]);

// Indentation (FR-21): continuation lines inside a WordDef or Quotation
// indent one unit; a line opening with the closer (`;` / `]`) dedents back.
const indentSpec = indentService.of((context, pos) => {
  const line = context.lineAt(pos);
  const tree = syntaxTree(context.state);
  let node = tree.resolveInner(pos, -1);
  let depth = 0;
  for (let n = node; n; n = n.parent) {
    if ((n.name === "WordDef" || n.name === "Quotation") && pos < n.to - 1) {
      depth++;
    }
  }
  const before = line.text.slice(0, pos - line.from).trimStart();
  if (before.startsWith(";") || before.startsWith("]")) {
    depth = Math.max(0, depth - 1);
  }
  return depth * 2;
});

// The public facet set (R-G: everything the app-side wrapper mounts).
// (Highlight application is the vendor facade's `syntaxHighlighting` call —
// one render surface, editor.css.)
export function tyu() {
  return [tyuLanguage, indentSpec];
}

export { tyuLanguage };
